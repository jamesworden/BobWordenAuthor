    <h1 class="font-semibold text-3xl md:text-4xl lg:text-5xl text-gray-800 mb-4">
      Progressive Mistakes of the French Revolution
    </h1>
    <p class="text-gray-600 mb-8">By: Bob Worden, Esq. © April 20, 2026</p>

    <div class="prose prose-lg max-w-none text-gray-700 space-y-4">
      <p>
        People often speak nonsense, only to look foolish
        later, like today's Progressive feminists standing up for
        Jihadists who would chop off feminist heads, if given the
        chance. Or well-meaning Billie Eilish offering to share her
        real estate with people she really did not want to share her
        digs with. Unexamined ideas and impractical thinking tend
        to create problems. If an ideology, any ideology, is going to
        succeed in the long term, it must be consistent with the
        practical realities. No matter what the system of
        government one chooses, capable leadership is still
        required.
      </p>

      <p>
        Listening to Lecture 26 of Thomas Childer's Great
        Book Audio Series on World War 2, I was pleased to learn
        that the ground was taken out beneath the similarly
        impractical Pacifist/Isolationist movements in the USA in
        the 1930s, when the Nazis conquered France in 1940.
        The majority of citizens in the USA immediately
        understood that the War presented real threats to America
        which had to be handled effectively. America's small army,
        which had ranked 19th, in size when the War started, was
        transformed into the most powerful Army in the World
        when the War ended 5 years later. the American people
        ignored ideologies in favor of modifying their goals in view
        of the practical necessities of the time.
      </p>

      <p>
        In todays' news, it appears that President Trump and
        his able advisors have set about to rearrange the world
        order in a practical way, by using America's power to help
        end conflicts around the world. Who knows, things could
        go sideways or backwards, due to bad luck or unforeseen
        events, but so far, even many of his enemies are admitting
        that President Trump's tough decisions are producing
        practical and beneficial results.
      </p>

      <p>
        Which brings me to back to the time when France
        was the second-most powerful country in the World, yet
        had an incapable King, whose poor decision-making
        opened the door to Progressives taking control of France.
        Ultimately the Progressives failed as they pursued
        impractical changes which were unpopular. This is the
        brief story of what happened: the failures of an inept
        Monarch opened the door to formation of a French
        Republic, leading to a series of Progressive changes to
        French society. The French people did not like many of
        the Progressive changes. After 10 years of chaos caused
        by the unfortunate choices of their new government, the
        French elected Napoleon to be their leader. He proved
        that he had the executive skill to make changes which
        most French people wanted. Napoleon was able to make
        himself Emperor for life (although later bad decisions took
        him out of power).
      </p>

      <p>
        Before the rise of Napoleon, back during the time the
        Guillotine was invented as a high-tech, supposedly
        humane tool, Progressive leaders used it to do away with
        their King and Queen in the very real "No Kings Day" of
        1791.
        Once they were operating the government,
        Progressives over-estimated their power to change
        entrenched French customs, believing that their education
        and knowledge entitled them to decide what was good for
        everyone else. They knew better than the people what
        was good for France.
      </p>

      <p>
        Some Progressive reforms lasted after the privileges
        of the Nobility and the Clergy were abolished. Religious
        freedom was granted to all Protestants. Slavery was
        abolished in France and some of its colonies, although
        even the Progressives knew that they could not
        completely shut down the money machine from the Sugar
        trade in their Caribbean colonies.
      </p>

      <p>
        After they took power in 1789, the Progressives
        imposed their idealist changes in the 3 French
        Constitutions created serially in the first six years of
        Progressive rule. Inspired by Enlightenment writers
        Rousseau and Voltaire, as well as the American
        Constitution, also created in 1789, Progressive thinkers
        saw the opportunity to remake France into a nation with
        freedom and equality.
      </p>

      <p>
        Back in 1789, the French people had good cause to
        be upset about how King Louis 16 and the French Nobility
        had been ruling France. Louis 16 was just not cut out for
        the role of King. Lacking the ability to discern right from
        wrong, he was sneaky and timid. Uncomfortable making
        decisions of any kind, he preferred to spend his time
        hunting (think of him as a "Prince Andrew" type.) But the
        French people believed their Kings were appointed by
        God and had faith in their Monarchy. They loved Louis16
        because he was their King.
      </p>

      <p>
        In 1789, most French were Catholics. They liked
        living with their traditions and customs, cherishing the
        annual rituals in the lives of their families and
        communities. But in 1789, they had become very unhappy
        due to the deterioration of the French economy.
        Guided by their financial advisors, Louis 16 and the
        French Nobles, had borrowed far too much money,
        spending like mad on themselves, and refusing to
        economize in the face of impending financial collapse.
        France had made huge profits from its colonies. But the
        Kings and Nobles kept spending much more than came in
        from taxes and tithes.
      </p>

      <p>
        Despite its poor financial condition, France even
        gave huge sums of money to support the American
        overthrow of British rule. Louis 16 had been convinced by
        American techno-wizard Ben Franklin to help fight against
        British King George 3. Louis 16 also loaned money France
        didn't have because he wanted revenge on King George
        3, who led Britain to win the Seven Years War and drive
        the French out of its North American colony.
      </p>

      <p>
        Increasing literacy in France exposed the people to
        the ideas of Enlightenment philosophers, themselves
        Progressives who were leading an assault on established
        religion.
        Feudalism had previously required the people at the
        bottom to pay oppressive amounts of money to the King,
        the Nobles and the Church. The Aristocracy (meaning the
        Nobles and Clergy) comprised only 3% of the 28 million
        population of France. They paid no taxes at all. The
        Nobles and Clergy received money squeezed out of the
        people at the bottom, who had no say whatsoever in the
        way France operated. The lack of food due to repeated
        droughts in the 1790s ignited the desperation of the
        common French people. Their anger was directed at these
        Aristocrats and French Royalty.
      </p>

      <p>
        The main issue was lack of food. It was not unusual
        for children to starve to death. Yet, the Nobility and the
        Clergy refused to reduce their burden on the people or to
        donate a share of their prosperity to ensure there was
        enough food for everyone. Rebellion had broken out in
        several different regions of France.
      </p>

      <p>
        Apparently not knowing what else to do, the King
        Louis 16 and the Aristocrats made an unwise decision:
        They notified the people that everyone should get together
        for meeting of the Estates General, a type of intervention
        meeting of all the people of France to try to correct
        problems for France. The last meeting of the Estates
        General had happened 167 years before. Chosen as a
        last resort by the Aristocrats, this Estates General meeting
        was supposed to get everyone together to discuss
        solutions, but the reality was that the Royalty had hoped to
        use the Estates General to force the starving people to
        pay even more money to the Aristocrats. It shows how out
        of touch the Royalty had become with the practical
        realities of the situation, which required the wealthy to
        make sacrifices, as the common people could give no
        more.
      </p>

      <p>
        Representatives from communities all over France
        attended the Estates General. They all met for several
        months in a huge room at the Palace in Versailles, a few
        miles outside of Paris, where the Kings of France had
        resided for 70 years. After the initial Estates General
        meetings went nowhere, the representatives of the
        common people recognized that the decisions made at the
        Estates General were going to end with a greater burden
        for them, the common people protested and walked out.
        They held their own separate meeting in a big room in a
        nearby building at Versailles, an indoor tennis court.
        Importantly, a substantial number of reform-minded Nobles
        also defected from the meeting of the King and Nobles
        main room. They agreed that the common people needed
        changes in their favor and joined the protestors' meetings.
        These Nobles felt that reductions of the burden on the
        common people were the only way to fix the economic
        problems. To preserve order, these liberal Nobles were
        ready to vote against their own pocketbooks and receive
        less income.
      </p>

      <p>
        The fact that some Nobles joined with the Protesters
        encouraged the Protesters, who had suspected that the
        King and Nobles had been hoarding grain and were selling
        it outside of France to make money, instead of helping the
        starving common people. There were lots of rumors and
        accusations flying all around, no different than the politics
        of today. Also, during this time, starving peasants had
        begun storming chateaus across France, undertaking
        insurrections against the Nobles in distant regions.
      </p>

      <p>
        Things finally boiled over in July of 1789, when Louis
        16 ordered a large army to be brought to Paris, possibly
        for use in a government crackdown on the people. Incited
        by this threat on July 14,1789, 1789, a mob in Paris
        attacked the big prison called the Bastille in the Paris city
        center. The mob had information that large quantities of
        gunpower were stored in the Bastille, which the mob
        wanted to use to defend against attack from the Army.
        After its initial assault, the Mob was allowed to enter the
        Bastille because many of the King's Army were also
        sympathetic to the cause of the common people.
      </p>

      <p>
        After removing the gunpowder, the mob began tearing
        down the Bastille stone by stone to the ground. (The fall
        of the Berlin Wall in 1989 is often compared to the fall of
        the Bastille.) After the Bastille had fallen, Louis 16 and the
        Nobles continued to meet at Versailles, as did the
        Protesters in their separate building, but no progress was
        made to resolve their differences. The shortage of food got
        worse.
      </p>

      <p>
        Then on October 4, 1789, upon hearing that the King
        was again bringing a large number of additional soldiers to
        the Paris region, a huge mob of peasants, aggressive men
        and women, marched to the King's palace at Versailles,
        wielding pikes, (long wooden shafts with blades attached
        to one end) waiving clubs and carrying stones for
        weapons. They wanted to obtain food and grain stored at
        the palace, to stave off starvation.
      </p>

      <p>
        Without being given orders to do so, the King's
        Guards at Versailles killed a few peasants. In response,
        the mob attacked and killed several of the King's Guards.
        To end the violence, Louis 16 finally gave in to the
        Common people. He implied that he would agree to create
        a constitutional monarchy to satisfy the mob (even though
        much later it was revealed that Louis 16 had no such
        intention at that time, he was just trying to mollify the mob
        to avoid further violence.)
      </p>

      <p>
        After Louis 16 said that he would make a deal to
        make a new form of government, the mob leaders insisted
        that the King and his Queen, Marie Antoinette,
        immediately leave Versailles and live in Paris itself, near
        the people. So, the King and Queen and the mob all
        traveled to Paris in a procession, bringing along many
        carts of grain with them from Versailles. The Royal Bakers
        marched along too, with loaves of bread placed on the end
        of pikes, which were lofted in celebration above the
        procession. At the same time, peasant men carried other
        pikes, upon which were raised the severed heads of the
        unfortunate King's Guards. The mob was sending a
        message to observers that they now had power over the
        King, but the King was still their King, but he would work
        with them to change the way the government operated.
      </p>

      <p>
        Delegates were chosen for a new National Assembly
        to be run by the people, and the Aristocrats who supported
        changing the way France was governed, now began
        meeting all together in one chamber in Paris daily, called
        the National Assembly.
        The Moderates controlled many of the delegates at
        the beginning of the National Assembly. Then, over time,
        the delegates split into smaller, like-minded groups of
        Progressives (who wanted no King), Moderates (who
        wanted a Constitutional Monarchy like Britain had) and
        Conservatives (who wanted a King). The Progressives sat
        at the left side of the large Assembly room, the
        Conservatives on the right side. The political terms "Left"
        and "Right" arose at this National Assembly and came to
        mean what they mean to us now.
      </p>

      <p>
        The creation of a new form of French government
        inspired formation of local political clubs which arose
        throughout France. The clubs of the poor and lower middle
        classes usually argued for radical changes. The French
        citizens with money wanted a conservative approach to
        reform. These local clubs met frequently. They sent
        messengers to their delegates in Paris about what they
        wanted in the new government.
      </p>

      <p>
        The National Assembly met regularly and came up
        with a constitution and communicated with the King about
        each day's events. But as time passed, King Louis 16
        became increasingly frustrated, as he did not really want
        to change things. Then, about two years after he and his
        Queen had moved to Paris, Louis 16 and his family tried to
        sneak out of France, feeling that he had become a captive
        and fearing that he would eventually be overthrown.
      </p>

      <p>
        It was later revealed that Louis 16 and his wife had
        secretly written to his wife's relatives—the Royalty of
        Austria—requesting that once Louis 16 and his family
        were safely in Austria, the Austrian army would invade and
        conquer France, then return Louis 16 to his unrestricted
        Kingly power.
      </p>

      <p>
        The idiocy of Louis 16's escape plan is consistent with
        his lack of common sense. The Royal Carpenters built him
        a giant luxury carriage (which by itself would draw
        anyone's attention) to transport the King and his entourage
        out of France. These Royals snuck away in the middle of
        the night, taking country roads once outside Paris, and
        headed for the border with Austria.
      </p>

      <p>
        Although Louis 16 and his entourage were dressed in
        common clothes, the gilded and leather trimmed carriage
        also carried 3 security officers riding on the roof, all
        dressed in matching yellow suits. Moreover, Louis 16 did
        not attempt to disguise his face at all, even though his face
        was familiar to many, having been pictured on the coins
        and paper currency widely circulated through France at
        that time.
      </p>

      <p>
        This gaudy carriage drew the attention of local
        authorities about 40 miles away from the Austrian border.
        After being identified by a man who had seen him at
        Versailles, Louis 16 admitted who he was, and the
        entourage was escorted back to Paris under guard. His
        treason and betrayal of France was exposed. It is no
        wonder that Louis 16 was ultimately executed by the
        Progressives in power at that time. The people were angry
        at his disloyalty, deceptions and treasonous actions. It was
        his own duplicity which convinced the National Assembly
        that they must execute Louis 16, as well as his queen,
        Marie Antoinette.
      </p>

      <p>
        The French people probably would have been better
        off if they had just named one of the King's relatives to be
        a new King to get things back on track, but at that time, it
        was all the rage by Progressives in France that science
        and knowledge was everything, that God was a lie, and
        that nobody needed any king, nor any faith in religion.
      </p>

      <p>
        Motivated by their convictions, the reformers in the
        new Constitutional government made extreme changes in
        France, which is when things got crazy. The Progressives
        had never been in power before. Many were intelligent
        and well-read but that didn't mean that they were practical
        or considered the ramifications of making extreme
        changes. They did not foresee the push-back which would
        result.
      </p>

      <p>
        The Progressives didn't have the extensive political
        experience possessed by the American Founders, who
        had the advantage of all being rich men with considerable
        government and business experience. The American
        ancestors had been running America for more than 100
        years. After the Americans luckily defeated the English in
        the American Revolution, thanks to help from Louis 16, the
        American Founders knew that they had to stick together
        for the new nation to survive. They already knew that they
        wanted the new America to be a lot like it was before,
        minus British control. It took them 6 years to put the new
        American Constitution in place, joining 13 separate
        colonies into one united government.
      </p>

      <p>
        Most of the Americans knew that they had to buy into
        the Liberty and Equality concept. Dissention in the fragile
        new United States of America risked being re-conquered
        by Britain or some other colonizing nation. The Americans
        had a much easier time sustaining their Constitution than
        the French would have, because the new American
        Government was run by the same people who had run the
        prior colonial governments. They knew what they wanted
        to do and what they needed to do.
      </p>

      <p>
        The French delegates had never been in power
        before. There was no unity of goal. There were too many
        people involved in the National Assembly to be able to get
        any reasonable consensus. (Not unlike our American
        Congress, who can argue endlessly whether American
        voters need to show reliable identification before being
        allowed to vote, when a school class of 12-year-olds could
        reach unanimous agreement that valid proof of the right to
        vote is a good idea in about 5 minutes.)
      </p>

      <p>
        By that time that Louis 16 and his wife were
        guillotined, much had already been changed in the way
        that the French people lived: The new government told
        the people that reason and equality were to be
        worshipped. Religion was superstition and should be
        shunned.
      </p>

      <p>
        The Progressives were very concerned that France
        was surrounded other countries, all ruled by their Kings, all
        of whom were worried about losing their own heads if their
        own citizens tried to take power as had the people of
        France.
      </p>

      <p>
        The new French leadership was antagonistic towards
        the neighboring Kings, who began to invade France, and
        attack from all directions. French leaders became
        paranoid that some local delegates were foreign agents,
        suspecting them of plotting against France, or of
        collaborating with the neighbor Kings. Acting on rumors
        and unproven accusations, the Progressive leaders
        started holding hearings in the National Assembly, quickly
        convicting those accused, crediting baseless allegations
        and unreliable proof, finding that people with other ideas
        were guilty of treason for supporting a return to monarchy,
        or even supporting a Constitutional monarchy instead of a
        republic. Once convicted, these former leaders were soon
        sent to the Guillotine for public execution, without valid
        proof or good reason for killing them, other than
        Progressive fear of invasion by neighboring armies and/or
        fear of internal skullduggery.
      </p>

      <p>
        Over time, the Moderate and Conservative leaders
        were able to take power away from the Progressives and
        started undertaking their own prosecutions of
        Progressives, again based upon flimsy accusations and
        suspect evidence, sending Progressive leaders to the
        guillotine in revenge, until eventually things finally settled
        down after six months of blood flowing daily, more than
        2,400 executions taking place in all, before this "Reign of
        Terror" ended.
      </p>

      <p>
        A smaller group of delegates then began running
        things for France, the majority having recognized that
        important decisions could be made more easily and
        quickly by having fewer people involved.
        Even though the Priests had previously been among
        the most important men in France, as they represented
        both Church and State, and had been at the center of
        many community functions and ceremonies, the Priests
        were discharged by the new government. The
        Progressives voted to take away all the lands owned by
        the Catholic Church, including the Monasteries and the
        convents. (As much as 10% of all French real estate had
        been owned by Catholic Church and other religious
        Orders.)
      </p>

      <p>
        The Progressives sold off the church lands and
        buildings to raise money to keep the new French
        government going, even though most of the French people
        were Catholic and believed in God. A lot of the common
        people were unhappy that their Catholic religion had been
        outlawed.
      </p>

      <p>
        The Progressives started paying priests salaries, if a
        priest agreed to swear allegiance to the French nation
        over God. About one-third of the priests refused to put the
        French Government over their God and quit. The
        Progressives believed that their nation was their God.
        Everything must be done that was best for the French
        nation. The government wanted everyone to call each
        other "Citizen", to reinforce the message that all were
        equal.
      </p>

      <p>
        They even wanted to do away with the formal "Vous"
        word and have everyone call each other the informal "Tu'
        for the same reason. (Does this "reform" sound familiar to
        the "compelled speech" sought by today's Progressives,
        trying to force people to use preferred gender terms?)
        The government even created one place of worship called
        "Church Without God". (This reminds me of the double-
        speak language of George Orwell's novel 1984.)
      </p>

      <p>
        People were also unhappy with the non-religious new
        French calendar the Progressives put in place instead of
        the old calendar (the old one which we still use today).
        The new French calendar started year 1 as the date that
        the King had been executed in 1793. The new calendar
        had only 10 months, as part of the new metric system
        which the Progressives introduced into France. ( I like the
        metric system, which was one of the good ideas of the
        French Progressives, which still has not been accepted in
        America.)
      </p>

      <p>
        All the months of the new French calendar were
        named after flowers, rivers and other non-religious items,
        for example, the month named "Thermador" was in the
        summer. Religious or Historical names were cancelled by
        the Progressives.
        The new leaders created 10-day weeks in the new
        calendar, so that people only had one day of rest every 10
        days, instead of one day of rest every 7 days. You can
        imagine how popular that was, not to mention the
        Progressives doing away with religious holidays and
        inserting political holidays in their place. The Church and
        the new calendar changes affected everyone and caused
        the greatest resistance to the new French government.
      </p>

      <p>
        Progressives reorganized all the political sub-divisions
        and remade the entire country, so that there were 84 equal
        sub-divisions, each with a county seat within 1 day walk
        for all citizens of that sub-division. If a big city was not
        centrally located within a sub-division, it was no longer a
        country seat, even if its location was on a big river which
        was suited to a high degree of trade. The intention was to
        make everything fair. The Progressives changed a lot
        more things to make the country fairer to everyone, too
        many to mention in this article, many of them impractical.
      </p>

      <p>
        As is true with American politics today, the
        countryside people of France were typically more
        conservative than those in the big cities. In several regions
        and several mid-size cities in France, the politics were
        highly conservative and the people there were very
        unhappy at all the changes which the Progressives forced
        upon them. There were other cities which became
        Progressive strongholds.
      </p>

      <p>
        The wars with the neighbor Kings did not stop. As
        time passed, a lot of French citizens became fed up with
        the changes they did not like, and looked to return to the
        old ways, like going to church on Sundays and celebrating
        Easter.
      </p>

      <p>
        Many of the Progressive changes were reversed by
        Napoleon after he came to power. He was a military
        genius, becoming a General at age 24. Napoleon
        possessed superior executive abilities and made good
        decisions, which had been sorely lacking in the French
        leadership. He was also very good at self-promotion and
        came to be famous for winning so many battles and
        dressing in a very conspicuous way when he walked in
        public so that everybody who saw him soon learned that
        he was the famous general. Napoleon became the head of
        all the armies and defeated the armies of the neighbor
        Kings and even took land away from most of them.
      </p>

      <p>
        It did not take long for Napoleon to be democratically
        elected as France's leader, taking control over all of
        France by himself and his advisors. He initially had many
        successes, including creating a fairer set of laws. He
        brought back the old calendar and allowed the people to
        worship God, although he was practical enough to know
        that he couldn't give any land back to the Catholic Church,
        which would have created a nightmare of conflict with the
        people who had purchased the Church property from the
        Progressives. Napoleon also reduced the number of items
        in the Progressive's Bill of Rights but left some of the
        Rights intact.
      </p>

      <p>
        Napoleon worked tirelessly and practically, quickly
        becoming even more popular. After a couple of years
        passed, he engineered his government so that he was
        able to make himself into an Emperor of the French
        Empire for life. This was not the democracy that the
        Progressives had been looking to create when they
        executed Louis 16 and Marie Antoinette.
      </p>

      <p>
        Napoleon could not rest on his accomplishments as
        the Kings of Europe still regarded Napoleon as anti-King,
        because Napoleon had come to power based on his own
        accomplishments and abilities. He wasn't born into
        leadership, as the foreign Kings had been. They saw him
        as a continuing threat and banded together to try to
        conquer Napoleon's huge army.
      </p>

      <p>
        Napoleon's great weakness was that he did not know
        when to stop invading other countries and concentrate on
        protecting the new borders he had given France. He
        engaged in combat with too many foreign Kings and finally
        was badly beaten by the Russians, resulting in the deaths
        of huge numbers of French soldiers, after which he was
        forced out of leadership.
      </p>

      <p>
        Eventually, France went back to having a King again.
        Many decades passed before democracy was again
        considered in France.
      </p>

      <p>
        I wanted to tell this story because there is turmoil in
        America today with Progressives seeking many changes
        which are unpopular with the majority of Americans, such
        as requiring solar-panels, windmills and reducing use of
        more economic carbon-based fuels, instead of letting the
        people chose their energy source from the marketplace;
        allowing crime to soar in the guise of protecting individual
        rights of the disadvantaged, whose communities are most
        harmed by Progressive refusals to take the repeat
        offenders and dangerously mentally ill off the streets; in
        favoring irresponsible people over the responsible; in
        choosing to appease foreign bad actors instead of
        confronting them to make changes.
      </p>

      <p>
        Today in America, Progressives make some of the
        same mistakes as the French made: It is not practical to
        try to force people to change their pronouns, which is
        confusing. (I still must take too much time to figure out
        who is the "their" when I run across that word in news
        stories.) It makes no sense to allow biological men to
        compete in woman's sports in view of the general disparity
        of strength and fragility. It is impractical to favor the needs
        of interest groups comprised of small numbers of people,
        making everyone else dance to their tune; to interfere with
        the safety of airline travel to force political change. It is
        impractical to create incentives which reward people more
        for not working than for working. It is impractical for
        American States to enact confiscatory taxes for take more
        money from the wealthy, which only reduces those States'
        tax revenues when the wealthy go elsewhere. Changes
        need to make economic sense and political sense, and
        they need to come slowly. People will put up with a lot, but
        everyone's patience runs out at some point.
      </p>

      <p>
        Lasting changes could have been made from the get-
        go in France without chopping off heads and making a lot
        of unnecessary and non-productive fuss. Something had
        to be done because the inept French King had been
        making bad financial decisions, choosing to favor the rich
        and powerful over his starving subjects.
      </p>

      <p>
        What France really needed was effective leadership,
        whether appointing a new King who understood what
        needed to be done to get the country on track, or creating
        a new government which was more fair to the common
        people, but at the same time, to be realistic, to change
        things in a measured way, and within the expectations of
        the majority of the people. The French Progressives'
        drastic changes didn't stick.
      </p>

      <p>
        In any event, the French Revolution would probably
        have succeeded if most of the people had been on board
        with creating a constitutional monarchy, as had worked in
        Britain. But in France, there were too many ideals pursued
        by leaders without practical sense to find workable
        solutions.
      </p>

      <p>
        Regardless of personal feelings and emotions,
        pursuing unpopular changes remains a political dead-end
        in America, just as it was in France 240 years ago.
      </p>

