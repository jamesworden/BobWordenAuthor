    <h1 class="font-semibold text-3xl md:text-4xl lg:text-5xl text-gray-800 mb-4">
      The Futility of Violence in the Quest for Change
    </h1>
    <p class="text-gray-600 mb-8">By: Bob Worden, Esq. © October 2, 2026</p>

    <div class="prose prose-lg max-w-none text-gray-700 space-y-4">
      <p>
        It has been a hell of a time, with so many shootings that you couldn't
        keep up with them. Sometimes we forget-- in the immediacy of the present-
        the extent of past American political violence. Our current times are almost
        subdued in comparison. I guess we have to admit that the American people
        have long-term memory issues Let us look back 150 years ago in the era of
        the Civil War, which even if you did know some of these true stories, you
        never some of the details or they have receded as you were bombarded
        with so much current information.
      </p>

      <p>
        Let's start with the conflicts between politicians in congress: In 1856,
        Texas congressman Philemon T. Herbert (his first name means "loving" or
        "affection") was upset when a waiter refused to serve him at a Washington,
        D.C. restaurant because the congressman had arrived after the established
        time for breakfast. In response to this misdemeanor in wait staff conduct,
        Congressman Herbert shot the waiter dead. The shooter was not crazy. He
        was just a southern bigot. The unfortunate waiter, an immigrant from
        Ireland, was a deplorable to nativist Texans. After this cold-blooded
        execution, Northern newspapers strongly denounced Congressman
        Herbert for this murder. Southern newspapers reported that the Irish waiter
        had gotten what he deserved. Tried for manslaughter, a Washington D.C.
        jury acquitted Herbert. Even then, injustice was emanating from
        Washington DC.
      </p>

      <p>
        Violence today is nothing new, despite the frantic claims of today's
        newscasters that the political situation in America has never been so bad.
        Yet, American democracy is not at presently in any greater danger nor
        threat than it has ever been. In fact, the functioning of American republican
        government shone has continued during the most difficult of times, even
        during the time of the American Civil War, which is exactly what our
        Founding Fathers designed our unique form of republican democracy to do.
      </p>

      <p>
        Law-breaking always begets further law breaking, if unchecked, and
        the same is true for violence. It does not matter whether the form of
        government is democracy, monarchy, socialism, or communism, taking the
        law into one's own hands tears at the very fabric of society. Individual
        violence is usually of little lasting consequence beyond the people involved,
        but a few instances of political assassination (Lincoln, the Kennedys, MLK,
        Charlie Kirk) or assassination attempts (Donald Trump) can completely
        alter the course of history in unforeseeable ways. The events of the past
        year have already demonstrated how chance plays a large role: If that
        assassin's bullet had killed President Trump, imagine how different today
        would be.
      </p>

      <p>
        Let's turn to the most famous example of political violence in the
        United States Congress, admittedly committed a few years before South
        Carolina fired on Fort Henry to ignite the Civil War: In 1856, Northern
        abolitionist Senator Charles Sumner mocked a South Carolina Senator,
        implying that this particular Senator and other leaders of the South were
        engaging with sexual relations with female slaves. Today, forensics have
        proved the Thomas Jefferson engaged himself in such distasteful actions.
        Hearing this accusation at this much more strait-laced time, a
        northern Senator who had watched this exchange on the Senate floor
        stated: "That damn fool is going to get himself killed by some other damn
        fool", which almost turned out to be a true prediction. Southern leaders had
        always claimed they descended from European Royalty making them elite.
        Under The Code of Chivalry, their honor allowed them to follow their own
        rules, without interference by the lower classes. They did not care about
        anyone else's freedom. If insulted, Southern leaders resorted to dueling to
        obtain satisfaction, even if it was technically illegal.
      </p>

      <p>
        Believing that Senator Sumner's accusations were so obviously
        grounds for violence, but that Sumner was not worthy of the honor of being
        challenged to a duel, an irate Southern congressman charged into the
        Senate two days later and repeatedly smashed Sumner with a heavy,
        hardwood, gold-knobbed cane, leaving him lying on the Senate floor
        covered in blood and permanently disabled. The blows were so violent that
        the cane had splintered and broken during this vicious assault. No one had
        dared to interfere or to stop the assaulting Congressman from leaving the
        Senate afterwards. Another Senator, confirming the violent attitudes of their
        elected officials, later commented that the only members of Congress who
        did not carry a knife and a loaded revolver were those who carried two
        revolvers. (One hopes that our current Congress need not be so motivated
        nor so well-armed to protect themselves from the other members).
      </p>

      <p>
        Overnight, both politicians involved in this incident became
        heroes for their respective political sides. Supporters gave the assaulting
        congressman gifts of several new canes including one inscribed "Hit Him
        Again", rewarding his defense of Southern honor and for his actions to
        discourage any more Abolitionist speeches which might risk triggering a
        slave revolt.
      </p>

      <p>
        The assaulting congressman was eventually arrested, convicted and
        fined for his actions. Although he resigned from office due to his
        conviction, the voters in his district soon returned him to Congress anyway.
        Two years later, Senator Sumner also returned to his position in the
        Senate, although unable to stand and suffering from brain damages, a
        visibly disabled reminder of the potential violence which can follow free
        speech.
      </p>

      <p>
        In another 1856 incident, Wisconsin congressman John Potter was
        challenged to duel by a Southern politician named Pryor. As the person
        challenged, Potter had the right to choose the weapons for the duel. He
        selected large-bladed Bowie knives. Pryor then backed down, refusing to
        duel with so vulgar a weapon as Potter had chosen.
        Republican supporters later honored Potter with the gift of a 7-foot-
        long Bowie Knife, inscribed to be used "For Pryor Engagements." (You can
        still see that 7-foot Bowie knife displayed at the Wisconsin Historical
        Society, unless historical revisionists have had it removed as an offending
        reminder of the past.)
      </p>

      <p>
        Even Abraham Lincoln was challenged to a duel early in his political
        career. Not as wise as he would later become, Lincoln had sent a letter to a
        newspaper ridiculing another politician. When that politician challenged
        Lincoln to duel, Lincoln chose the longest obtainable broad swords for
        weapons. When the 6-foot, 4-inch-tall Lincoln swung his broad sword high
        and cut right through a tree branch above his 5 foot 9-inch-tall adversary,
        demonstrating the extent of Lincoln's reach and power, and a truce was
        immediately called. Lincoln was no fool. Refusal to duel would have made
        Lincoln look weak and dishonorable. Instead, he displayed the great
        physical strength he developed when he was a young man, splitting wood
        with an axe making railroad ties. This was Lincoln's version of "fight, fight,
        fight", which helped convince voters that Lincoln was admirably
        courageous.
      </p>

      <p>
        Before the time of the Civil War, Chief Supreme Court Justice Roger
        Taney's legal opinion upheld the validity of the Fugitive Slave Act, which
        passed to benefit slave owners in the South. However, this Act's unfair
        provisions actually worked against Southern interests as the unfairness of
        the law increased opposition to slavery in the North; The Fugitive Slave Act
        made criminals of anyone who assisted slaves on their way to freedom in
        Canada, where slavery was prohibited. This obviously unjust law was
        sanctioned by the highest court in America. It enabled the seizing and
        kidnapping of free blacks in the North to return them to the Southern
        slavery. Although passage of this Act enraged Abolitionists, just the same
        the way Supreme Court decisions can enrage people today, although
        responding in violence was rejected by most Abolitionists.
      </p>

      <p>
        In the South, as the conflict in values increased, so did the violence.
        In 1857, an Anti-Black southerner named Hinton Rowan Helper had sought
        to "whiten" Southern society by publicizing his plan to outlaw slavery and
        deport all freed slaves from the USA. Helper wrote a best-selling
        book called The Impending Crisis, with was banned throughout the South.
        Importing Helper's book into Southern states risked the death penalty.
        Mobs beat or lynched anyone who supported Helper in his plan to end
        slavery by transporting all the slaves out of America. In Texas, a mob
        burned a peddler alive for selling copies of Helper's book. This extreme
        form of "cancellation" long predates our current cancel culture, where
        individuals also resort to violence. For example, the shooter who hit
        President Trump's ear appears to have wanted to eliminate a person he
        perceived as a threat to transgender rights.
      </p>

      <p>
        As the onset of the Civil War loomed in 1860, a series of unusual
        barn fires triggered The Texas Insurrection Panic. Rumors had spread that
        rebellious slaves were setting barn fires. These rumors also claimed that
        slaves were poisoning well water as a prelude to an imminent slave
        insurrection.
        Motivated by these rumors, Texas vigilantes killed more than 75
        blacks and anti-slavery white suspects. Later, the fires were proved to have
        been ignited by unusually hot weather and improper storage of grain. No
        one was ever punished for the violence. Also in 1860, In Fort Worth, a
        vocal anti-slavery Methodist Minister named Anthony Bewley was hanged
        by Texas vigilantes who scraped the flesh off his bones, adorned his
        skeleton with a sign naming it "The Old Abolitionist", and propped it up as
        gruesome warning on the roof of a store in that city. (No one removed the
        skeleton until 7 years later, long after the Civil War ended.)
      </p>

      <p>
        Violence was also undertaken in the North. During the Civil War, in
        New York City, a military draft was organized to replace the massive
        number of Union soldiers who had been killed in battle at Gettysburg. Irish
        immigrants were to be included in the draft. When the announcement of the
        draft was made, the Irish formed mobs and brought mayhem to the city,
        destroying draft offices, newspaper offices, and the homes of Abolitionists.
        These mobs roved though poor neighborhoods, torturing, lynching and
        drowning Blacks. They looted, burned police stations and Black
        orphanages.
      </p>

      <p>
        Recent immigrants with little money, the mostly Catholic Irish believed
        that the wealthy Protestants who ran New York City were responsible for
        the poor conditions in which the Catholics were living. There was no way
        these poor Irish would willingly fight in a War for Black freedom, which
        would result in large numbers of Blacks migrating north to compete with the
        Irish for paying work. After 5 or 6 days of violent chaos, Union troops
        restored order. The grotesque violence of the riots worked against the
        motives of the Irish, by convincing other New Yorkers to accept that the
        evils of slavery needed to end for social stability to return. In the end, like
        with the Black Lives Matter riots of our times, the violence and destruction
        worked against the interests of their communities. There was no lasting
        positive effect of this political violence. There never is. Political change
        takes place pursuant to the efforts of very large numbers of people.
        Individual violence is ineffective as a method to create lasting changes.
      </p>

      <p>
        In a New York City plot, in 1864, a local newspaper learned that
        Confederate President Jefferson Davis had secretly hired Canadian agents
        to plant fire bombs in hotels, theaters, and the P.T. Barnum Museum in New
        York City. Davis wanted to kill thousands of New York City civilians, which
        he believed would cause Northerners to end the War, and grant the
        Confederacy the secession it sought. The firebombs turned out to be duds,
        although most New Yorkers panicked when they learned about the scope
        of the attempt. This underhanded Confederate plot to injure civilians
        enraged New Yorkers and hardened their resolve to defeat the
        Confederates, which was another backfire, just the opposite of what
        Jefferson Davis had intended.
      </p>

      <p>
        Similarly, President Andrew Johnson's failure to prevent violence and
        discord in the South following the end of the Civil War motivated voters to
        elect Republicans to every governorship. Republicans also won the
        majority in Congress in the mid-term elections of 1866. Johnson's refusal to
        prevent criminal action against Blacks resulted in Republicans taking power
        away from the people Johnson failed to control.
      </p>

      <p>
        I have detailed these events to help deter people from trying to take
        the law into their own hands. People may chose to undertake violent
        actions, but these often energize the opposition. Highly effective in harming
        or destroying the lives of those unlucky enough to be at the wrong place at
        the wrong time, thugs and assassins choose their targets, seeking to
        change the power structures in America. But didn't the guy who shot, but
        failed to kill President Trump only help President Trump to be re-elected?
        Didn't the guy who shot Charlie Kirk make Charlie Kirk's message ten times
        more popular?
      </p>

      <p>
        These are thoughts we need to consider: Voting is the only action
        which changes how America operates. We believe that the right to vote is
        precious because it is so powerful, a great tool to help the American people
        to make required changes. But to try to sway voters by saying that a
        politician "is dangerous" or "needs to be stopped" in America must be made
        solely as an encouragement to vote for someone else. Every politician
        must clarify that he or she is not encouraging violence to make change.
        Impassioned political statements must be clearly avoid being
        interpreted as calls for violence. The American republican democracy
        continues to be the best form of government ever invented, as renegade
        factions do not have the power to harm it, due to the checks and balances
        it provides. Thoughtful voting, not violence, will create a better America.
      </p>

      <p class="italic text-sm mt-8">
        Note: The primary source for the stories contained here is a wonderful book
        by University of Virginia Professor Alan Taylor, American Civil Wars. After
        reading this book and Alan Taylor's prior American Colonies: The Settling
        of America, I remain stunned by the extent of violence and psychopathy
        described in these works. If anyone thinks our times are the worst ever,
        read those books to learn the terrible extent of past North American
        violence. Professor Taylor is prominently featured in the recent Ken
        Burns/PBS documentary celebrating the 250th Anniversary of the American
        Revolution.
      </p>
